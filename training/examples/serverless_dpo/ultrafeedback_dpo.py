#!/usr/bin/env python3
"""Serverless DPO (Direct Preference Optimization) -- a self-contained,
Tinker-style loop.

This example runs preference training against Fireworks **serverless
training**: you connect to a shared, already-running pooled trainer and get
back a Tinker-compatible training client. There is nothing to provision.

It is the Fireworks port of Tinker's DPO recipe
(``tinker_cookbook/preference/train_dpo.py``). The loop is identical:

    service = FiretitanServiceClient(base_url=".../training/v1/serverless")
    training_client = service.create_lora_training_client(base_model, rank)
    # Reference = frozen snapshot of the step-0 weights (zero-init LoRA, so
    # this IS the base model) -- the same anchor Tinker uses.
    ref_path = training_client.save_weights_for_sampler("dpo-ref").result().path
    reference_client = service.create_sampling_client(model_path=ref_path)
    for step in range(steps):
        # datums interleaved [chosen_0, rejected_0, chosen_1, rejected_1, ...]
        ref_logprobs = [reference_client.compute_logprobs(seq) for seq in batch]
        training_client.forward_backward_custom(datums, dpo_loss_fn).result()
        training_client.optim_step(adam).result()

The loss (Rafailov et al., 2023) is the shared ``make_batch_dpo_loss_fn`` --
the same math the managed ``recipes/dpo_loop.py`` uses::

    L = -log sigmoid(beta * [(pi_chosen - ref_chosen) - (pi_rejected - ref_rejected)])

The default dataset is UltraFeedback binarized preferences (same source as
Tinker's ultrafeedback DPO builder), generated by ``prepare_data.py``.
``margin`` and ``accuracy`` should climb; ``dpo_loss`` should fall from
~0.693 (ln 2).

Usage::

    export FIREWORKS_API_KEY=fw_...
    python -m examples.serverless_dpo.prepare_data     # one-time data download
    python -m examples.serverless_dpo.ultrafeedback_dpo

    # resume a previous run's checkpoint in a brand-new process
    python -m examples.serverless_dpo.ultrafeedback_dpo \\
        --resume-from <account>/<run-id>/<checkpoint-name>
"""

