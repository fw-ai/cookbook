"""Deterministic generator for the cookbook SDK fallback snapshots.

``training/_tokenizer_identity_snapshot.py`` and
``training/utils/_kimi_native_tokenizer_snapshot.py`` are byte-exact
generated copies of the SDK sources of truth behind a static header, used by
the cookbook wrappers only as the fallback when the installed SDK predates
the matching capability marker. Regenerate after any SDK-side change:

    python training/tests/_tokenizer_identity_snapshot_generator.py
"""

from __future__ import annotations

import hashlib
from pathlib import Path

SDK_RELATIVE_PATH = "python-sdk/src/fireworks/training/sdk/tokenizer_identity.py"
SNAPSHOT_RELATIVE_PATH = "cookbook/training/_tokenizer_identity_snapshot.py"
KIMI_SDK_RELATIVE_PATH = "python-sdk/src/fireworks/training/sdk/kimi_native_tokenizer.py"
KIMI_SNAPSHOT_RELATIVE_PATH = "cookbook/training/utils/_kimi_native_tokenizer_snapshot.py"

_HEADER = """# TEMPORARY DUPLICATION: generated byte-exact snapshot of
# fireworks.training.sdk.tokenizer_identity (SDK source of truth), used by
# training.tokenizer_identity only as the fallback when the installed SDK
# predates TOKENIZER_IDENTITY_POLICY_CAPABILITY. Regenerate with
# python training/tests/_tokenizer_identity_snapshot_generator.py.
"""

_KIMI_HEADER = """# TEMPORARY DUPLICATION: generated byte-exact snapshot of
# fireworks.training.sdk.kimi_native_tokenizer (SDK source of truth), used by
# training.utils.kimi_native_tokenizer only as the fallback when the installed
# SDK predates KIMI_NATIVE_TOKENIZER_CAPABILITY. Regenerate with
# python training/tests/_tokenizer_identity_snapshot_generator.py.
"""


def generate_snapshot_text(sdk_source: str) -> str:
    """Return the exact snapshot content for a given SDK module source."""
    return _HEADER + sdk_source


def generate_kimi_snapshot_text(sdk_source: str) -> str:
    """Generate the same implementation using Cookbook's installed vendors."""
    return _KIMI_HEADER + sdk_source.replace(
        "fireworks.training.sdk._vendored.kimi_k3.encoding_k3",
        "training.renderer._vendored.kimi_k3.encoding_k3",
    ).replace(
        "fireworks.training.sdk._vendored.kimi_k31.encoding_k3",
        "training.renderer.tito._vendored.kimi_k31.encoding_k3",
    )


def generate_sdk_encoder_text(source: str, profile: str) -> str:
    """Apply only SDK lint's import order and an unused local-name rename."""
    pins = {
        "kimi_k3": "b9cb7ae100fed34b9337f80dacee5abbf7e261fe9b74bc0e76366701d46f5333",
        "kimi_k31": "367f0a7ab8800f78f7e09dc31e58544ee7fc46eea992ea05b32d53506a921cc5",
    }
    if hashlib.sha256(source.encode("utf-8")).hexdigest() != pins[profile]:
        raise ValueError(f"unreviewed {profile} encoder source")
    original_imports = "from dataclasses import dataclass\nfrom typing import Any, Iterable, Optional"
    sdk_imports = "from typing import Any, Iterable, Optional\nfrom dataclasses import dataclass"
    assert source.count(original_imports) == 1
    source = source.replace(original_imports, sdk_imports)
    if profile == "kimi_k3":
        original_loop = "for message_index, message in enumerate(messages):"
        assert source.count(original_loop) == 1
        source = source.replace(original_loop, "for _message_index, message in enumerate(messages):")
    return source


def main() -> int:
    public_repos = Path(__file__).resolve().parents[3]
    sdk_path = public_repos / SDK_RELATIVE_PATH
    snapshot_path = public_repos / SNAPSHOT_RELATIVE_PATH
    snapshot_path.write_text(generate_snapshot_text(sdk_path.read_text(encoding="utf-8")), encoding="utf-8")
    print(f"wrote {snapshot_path}")
    kimi_sdk_path = public_repos / KIMI_SDK_RELATIVE_PATH
    kimi_snapshot_path = public_repos / KIMI_SNAPSHOT_RELATIVE_PATH
    kimi_snapshot_path.write_text(
        generate_kimi_snapshot_text(kimi_sdk_path.read_text(encoding="utf-8")),
        encoding="utf-8",
    )
    print(f"wrote {kimi_snapshot_path}")
    # Packaged copies keep SDK message sampling standalone. They are reviewed
    # assets, not a third implementation. Keep the source pins and apply only
    # deterministic SDK lint adaptations; never suppress the SDK's checks.
    for profile, source_relative in (
        ("kimi_k3", "cookbook/training/renderer/_vendored/kimi_k3"),
        ("kimi_k31", "cookbook/training/renderer/tito/_vendored/kimi_k31"),
    ):
        destination = public_repos / "python-sdk/src/fireworks/training/sdk/_vendored" / profile
        destination.mkdir(parents=True, exist_ok=True)
        for filename in ("__init__.py", "encoding_k3.py", "LICENSE", "PROVENANCE.md"):
            data = (public_repos / source_relative / filename).read_bytes()
            if filename == "encoding_k3.py":
                data = generate_sdk_encoder_text(data.decode("utf-8"), profile).encode("utf-8")
            if filename == "PROVENANCE.md":
                encoder = generate_sdk_encoder_text(
                    (public_repos / source_relative / "encoding_k3.py").read_text(encoding="utf-8"), profile
                )
                adaptation = (
                    "# SDK packaged-encoder adaptation\n\n"
                    "The manifest below describes the reviewed upstream source. The SDK copy "
                    "differs only by the existing Ruff import order and, for K3, renaming the "
                    "unused loop index to `_message_index`. No template/token semantics change "
                    "and no lint rule is disabled. Regenerate using the tokenizer snapshot generator.\n\n"
                    f"SDK packaged SHA-256: `{hashlib.sha256(encoder.encode('utf-8')).hexdigest()}`.\n\n"
                    "## Original source manifest\n\n"
                )
                data = adaptation.encode("utf-8") + data
            if filename == "LICENSE":
                # Preserve all legal text; normalize only trailing whitespace
                # on newly packaged copies so git diff --check remains clean.
                data = b"\n".join(line.rstrip() for line in data.split(b"\n"))
            (destination / filename).write_bytes(data)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
